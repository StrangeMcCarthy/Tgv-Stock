    AppLanguage.ENGLISH -> enStrings
}

// ─── Category translation helpers ───────────────────────────────────────────
fun Strings.localizeCategory(rawCategory: String): String = when (rawCategory) {
    "Bières" -> prodCatBeers
    "Guinness" -> prodCatGuinness
    "Gazeuses" -> prodCatSodas
    "Canettes" -> prodCatCans
    "Alcopops" -> prodCatAlcopops
    "Eaux" -> prodCatWaters
    "Non-Alcoolisé" -> prodCatNonAlcoholic
    else -> rawCategory
}

